#!/usr/bin/env bash
# =============================================================================
# lib.sh (post 07): sourced by the post 07 scripts, not executed.
#
# Reuses post 04's helpers (and through them posts 01-03: settings, lab user,
# db_sqlplus as SYSDBA in the container) and adds the post 07 settings and
# helpers: running SQL as the application user, and measuring a query.
# The agent's account is not touched in this post.
# =============================================================================

# Folder of the post 07 scripts.
POST07_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# Post 04 helpers (and posts 01-03 through them).
# shellcheck source=../post-04-auditing-the-agent/lib.sh
source "${POST07_DIR}/../post-04-auditing-the-agent/lib.sh"

# Where this post keeps its evidence.
POST07_OUT="${OUTPUT_DIR}/post-07-sql-tuning"
# The application user's password: generated by 01_setup.sh, mode 600,
# deleted by 99_cleanup.sh. Same place as the database password from post 01.
TUNE_PWD_FILE="${HOME}/.config/oralab/tune_lab_pwd"
# The slow query, exactly as the application runs it.
QUERY_ORIGINAL="${POST07_DIR}/query_original.sql"
# What the agent gets: query, plan, DDL, statistics (written by 03_context_pack.sh).
CONTEXT_PACK="${POST07_OUT}/context_pack.txt"

# Load posts 01-04 settings, then post 07 settings.
load_post07_config() {
    # Everything from posts 01-04.
    load_post04_config
    # Post 07 defaults.
    # shellcheck source=env.example
    source "${POST07_DIR}/env.example"
    # Post 07 local overrides, if any.
    if [[ -f "${POST07_DIR}/.env" ]]; then
        # shellcheck disable=SC1091
        source "${POST07_DIR}/.env"
    fi
    # The schema name goes into SQL: a plain upper-case Oracle identifier only.
    [[ "${TUNE_SCHEMA}" =~ ^[A-Z][A-Z0-9_]{0,29}$ ]] || die "TUNE_SCHEMA must be an upper-case Oracle identifier."
    # Numbers go into SQL: whole numbers only.
    local v
    for v in TUNE_ROWS MEASURE_RUNS STA_TIME_LIMIT; do
        [[ "${!v}" =~ ^[1-9][0-9]*$ ]] || die "${v} must be a positive whole number."
    done
    # At least 100 days of data, so the query's single day is a small slice.
    (( TUNE_ROWS >= 100000 )) || die "TUNE_ROWS must be at least 100000."
    # The evidence folder exists from here on.
    mkdir -p "${POST07_OUT}"
}

# The substitution variables every post 07 SQL file may use, one "define" per line.
post07_defines() {
    echo "define tune_schema = ${TUNE_SCHEMA}"
    echo "define tune_rows   = ${TUNE_ROWS}"
    echo "define sta_limit   = ${STA_TIME_LIMIT}"
}

# Run a SQL file from this folder as SYSDBA in the container, with the post 07
# defines (and any extra "define" lines) first, all through stdin.
# Usage: run_post07_sql <file.sql> [extra "define name = value" lines...]
run_post07_sql() {
    local file="${POST07_DIR}/$1"
    shift
    [[ -f "${file}" ]] || die "SQL file not found: ${file}"
    {
        post07_defines
        local extra
        for extra in "$@"; do echo "${extra}"; done
        cat "${file}"
    } | db_sqlplus
}

# The application user's password (from 01_setup.sh).
tune_password() {
    [[ -f "${TUNE_PWD_FILE}" ]] || die "no ${TUNE_SCHEMA} password: run ./01_setup.sh first."
    tr -d '[:space:]' < "${TUNE_PWD_FILE}"
}

# Measure a query AS THE APPLICATION USER: flush the PDB's shared pool (so a
# new index, a profile or a rewrite gets a fresh plan), run the query
# MEASURE_RUNS times, and keep the LAST execution's actual plan with runtime
# statistics (DBMS_XPLAN.DISPLAY_CURSOR, ALLSTATS LAST). The raw output goes
# to <outfile>; parse_measure.py turns it into a summary.
# Usage: measure_query <query file> <outfile>
measure_query() {
    local query="$1" out="$2"
    [[ -f "${query}" ]] || die "query file not found: ${query}"
    # A fresh start for every measurement (lab only): no plan left from before.
    db_sqlplus <<'SQL' >/dev/null
whenever sqlerror exit failure
alter session set container = FREEPDB1;
alter system flush shared_pool;
exit
SQL
    {
        post07_defines
        echo "define tune_pwd = $(tune_password)"
        # Connect as the application user (the password only travels through stdin).
        cat <<'SQL'
whenever sqlerror exit failure
set verify off feedback off heading off pagesize 0 linesize 300 trimspool on tab off
connect &tune_schema/"&tune_pwd"@//localhost:1521/FREEPDB1
-- Row source statistics for every execution: what DISPLAY_CURSOR's ALLSTATS needs.
alter session set statistics_level = all;
-- Off, or the last statement would be DBMS_OUTPUT's, not the query.
set serveroutput off
SQL
        # The query, MEASURE_RUNS times, each result between markers.
        local i
        for (( i = 1; i <= MEASURE_RUNS; i++ )); do
            echo "prompt #RESULT_BEGIN#"
            cat "${query}"
            echo "prompt #RESULT_END#"
        done
        cat <<'SQL'
-- The statement this session ran last: the query (PROMPT runs no SQL).
column m_id new_value m_sql_id noprint
column m_ch new_value m_child  noprint
select prev_sql_id m_id, prev_child_number m_ch from v$session where sid = sys_context('userenv', 'sid');
select 'SQL_ID=&m_sql_id CHILD=&m_child' from dual;
-- Its actual plan, with the last execution's rows, time and buffer gets.
select plan_table_output from table(dbms_xplan.display_cursor('&m_sql_id', &m_child, 'ALLSTATS LAST'));
select '#MEASURE_COMPLETE#' from dual;
exit
SQL
    } | podman exec -i "${DB_CONTAINER}" sqlplus -s -L /nolog > "${out}" 2>&1 || {
        tail -20 "${out}" >&2
        die "measurement failed: see ${out}"
    }
    grep -q '#MEASURE_COMPLETE#' "${out}" || { tail -20 "${out}" >&2; die "measurement incomplete: see ${out}"; }
}
