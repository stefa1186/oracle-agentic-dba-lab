#!/usr/bin/env bash
# =============================================================================
# lib.sh (post 08): sourced by the post 08 scripts, not executed.
#
# Reuses post 04's helpers (and through them posts 01-03: settings, lab user,
# db_sqlplus as SYSDBA in the container) and adds the post 08 settings and
# helpers: running SQL as the application user RAG_LAB.
# The agent's account is not touched in this post.
# =============================================================================

# Folder of the post 08 scripts.
POST08_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# Post 04 helpers (and posts 01-03 through them).
# shellcheck source=../post-04-auditing-the-agent/lib.sh
source "${POST08_DIR}/../post-04-auditing-the-agent/lib.sh"

# Where this post keeps its evidence.
POST08_OUT="${OUTPUT_DIR}/post-08-vector-search-team-notes"
# The application user's password: generated by 02_setup.sh, mode 600,
# deleted by 99_cleanup.sh.
RAG_PWD_FILE="${HOME}/.config/oralab/rag_lab_pwd"
# The folder inside the container the database reads the model from.
CONTAINER_MODEL_DIR=/tmp/post08_model
# The questions and the team notes.
QUESTIONS="${POST08_DIR}/questions.txt"
TEAM_NOTES_DIR="${POST08_DIR}/team_notes"

# Load posts 01-04 settings, then post 08 settings.
load_post08_config() {
    # Everything from posts 01-04.
    load_post04_config
    # Post 08 defaults.
    # shellcheck source=env.example
    source "${POST08_DIR}/env.example"
    # Post 08 local overrides, if any (MODEL_SHA256 belongs there).
    if [[ -f "${POST08_DIR}/.env" ]]; then
        # shellcheck disable=SC1091
        source "${POST08_DIR}/.env"
    fi
    # Names go into SQL: plain upper-case Oracle identifiers only.
    local v
    for v in RAG_SCHEMA MODEL_NAME; do
        [[ "${!v}" =~ ^[A-Z][A-Z0-9_]{0,29}$ ]] || die "${v} must be an upper-case Oracle identifier."
    done
    [[ "${TOP_K}" =~ ^[1-9][0-9]?$ ]] || die "TOP_K must be a whole number from 1 to 99."
    [[ "${MODEL_FILE}" =~ ^[A-Za-z0-9_.-]+$ ]] || die "MODEL_FILE must be a plain file name."
    # The evidence folder exists from here on.
    mkdir -p "${POST08_OUT}"
}

# The substitution variables every post 08 SQL file may use.
post08_defines() {
    echo "define rag_schema = ${RAG_SCHEMA}"
    echo "define model_name = ${MODEL_NAME}"
    echo "define model_file = ${MODEL_FILE}"
    echo "define model_dir  = ${CONTAINER_MODEL_DIR}"
    echo "define top_k      = ${TOP_K}"
}

# Run a SQL file from this folder as SYSDBA in the container, defines first,
# all through stdin.
# Usage: run_post08_sql <file.sql> [extra "define name = value" lines...]
run_post08_sql() {
    local file="${POST08_DIR}/$1"
    shift
    [[ -f "${file}" ]] || die "SQL file not found: ${file}"
    {
        post08_defines
        local extra
        for extra in "$@"; do echo "${extra}"; done
        cat "${file}"
    } | db_sqlplus
}

# The application user's password (from 02_setup.sh).
rag_password() {
    [[ -f "${RAG_PWD_FILE}" ]] || die "no ${RAG_SCHEMA} password: run ./02_setup.sh first."
    tr -d '[:space:]' < "${RAG_PWD_FILE}"
}

# Run SQL from stdin AS THE APPLICATION USER (connects itself; the password
# only travels through stdin). The defines come first.
# Usage: ... | run_as_rag
run_as_rag() {
    {
        post08_defines
        echo "define rag_pwd = $(rag_password)"
        echo "whenever sqlerror exit failure"
        echo "set verify off feedback off"
        echo 'connect &rag_schema/"&rag_pwd"@//localhost:1521/FREEPDB1'
        cat
    } | podman exec -i "${DB_CONTAINER}" sqlplus -s -L /nolog
}

# One question from questions.txt by id: "<expected team note>|<question>".
question_by_id() {
    awk -F'|' -v id="$1" '$1 ~ /^Q *$/ { gsub(/^ +| +$/, "", $2); if ($2 == id) { gsub(/^ +| +$/, "", $3); q = $4; sub(/^ +/, "", q); print $3 "|" q } }' "${QUESTIONS}"
}

# The ids of all questions, in file order.
question_ids() {
    awk -F'|' '$1 ~ /^Q *$/ { gsub(/^ +| +$/, "", $2); print $2 }' "${QUESTIONS}"
}
